import assert from "node:assert/strict";
import {glassKey,normalizeGlass,readGlass,saveGlass} from "../src/lib/liquidGlass.js";
const values=new Map(),storage={getItem:key=>values.get(key)??null,setItem:(key,value)=>values.set(key,value)};
assert.equal(readGlass("first",storage),"off");
assert.equal(normalizeGlass("garbage"),"off");
assert.deepEqual(saveGlass("first","clear",storage),{mode:"clear",persisted:true});
assert.equal(readGlass("first",storage),"clear");
assert.equal(readGlass("second",storage),"off","accounts do not share appearance");
saveGlass("second","tinted",storage);
assert.equal(readGlass("first",storage),"clear");
assert.equal(readGlass("second",storage),"tinted");
assert.notEqual(glassKey("first"),glassKey("second"));
const blocked={getItem(){throw Error("blocked")},setItem(){throw Error("blocked")}};
assert.deepEqual(saveGlass("blocked","tinted",blocked),{mode:"tinted",persisted:false});
assert.equal(readGlass("blocked",blocked),"tinted","blocked storage keeps the current session usable");
assert.equal(readGlass("other",blocked),"off");
values.delete(glassKey("first"));assert.equal(readGlass("first",storage),"off","removing preference restores default");
values.set(glassKey("first"),"invalid");assert.equal(readGlass("first",storage),"off");
assert.deepEqual(saveGlass("first","invalid",storage),{mode:"off",persisted:true});
console.log("PASS Liquid Glass defaults, account separation, persistence, invalid values and blocked-storage fallback");
