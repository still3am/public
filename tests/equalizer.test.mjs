import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync('src/lib/equalizer.js','utf8');
const {normalizeMixer,mixerHeadroom,smoothAudioParam,DEFAULT_MIXER,EQ_PRESETS}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
assert.deepEqual(normalizeMixer(null),DEFAULT_MIXER);
const migrated=normalizeMixer({bass:Infinity,beat:18,vocals:-48,treble:"12",boost:3});
assert.equal(migrated.bass,0);assert.equal(migrated.beat,12);assert.equal(migrated.vocals,-12);assert.equal(migrated.treble,0);assert.equal(migrated.boost,1.5);
assert.equal(mixerHeadroom({...migrated,enabled:false}),1);
assert.equal(mixerHeadroom(DEFAULT_MIXER),1);
assert.ok(mixerHeadroom({...DEFAULT_MIXER,bass:6})<.51);
for(const preset of EQ_PRESETS)assert.ok(mixerHeadroom(normalizeMixer(preset.values))<=1);
const calls=[];
smoothAudioParam({cancelScheduledValues:t=>calls.push(['cancel',t]),setTargetAtTime:(v,t,c)=>calls.push(['smooth',v,t,c])},6,10);
assert.deepEqual(calls,[['cancel',10],['smooth',6,10,.025]]);
const player=readFileSync('src/context/PlayerContext.jsx','utf8');
assert.ok(player.indexOf('masterGainRef.current = master;')<player.indexOf('applyMixerToGraph(mixerRef.current);'),'saved settings apply after graph refs exist');
assert.ok(player.includes('beatF1.connect(vocalsF1);'));
assert.ok(player.includes('vocalsF1.connect(trebleF);'));
console.log('PASS equalizer defaults, migration/clamping, bypass, headroom, presets, smoothing and startup graph ordering');
